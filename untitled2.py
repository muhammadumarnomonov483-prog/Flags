import matplotlib.pyplot as plt
import matplotlib.patches as patches

fig, ax = plt.subplots(figsize=(10, 5))

ax.add_patch(patches.Rectangle((0, 0), 12, 2, color='green'))
ax.add_patch(patches.Rectangle((0, 2), 12, 2, color='white'))
ax.add_patch(patches.Rectangle((0, 4), 12, 2, color='black'))
ax.add_patch(patches.Polygon(
    [(0, 0), (0, 6), (4, 3)], color='red'
))

ax.set_xlim(0, 12)
ax.set_ylim(0, 6)
ax.axis('off')

plt.show()