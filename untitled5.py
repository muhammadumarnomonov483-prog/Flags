import matplotlib.pyplot as plt
import matplotlib.patches as patches

fig, ax = plt.subplots(figsize=(10, 5))

# Oq rang
ax.add_patch(patches.Rectangle(
    (0, 4), 12, 2, color='white'
))

# Ko‘k rang
ax.add_patch(patches.Rectangle(
    (0, 2), 12, 2, color='#0039A6'
))

# Qizil rang
ax.add_patch(patches.Rectangle(
    (0, 0), 12, 2, color='#D52B1E'
))

ax.set_xlim(0, 12)
ax.set_ylim(0, 6)
ax.axis('off')

plt.show()