import matplotlib.pyplot as plt
import matplotlib.patches as patches

fig, ax = plt.subplots(figsize=(10, 5))

# 13 ta qizil va oq chiziq
for i in range(13):
    color = '#B22234' if i % 2 == 0 else 'white'
    ax.add_patch(patches.Rectangle(
        (0, i * 6/13), 12, 6/13, color=color
    ))

# Ko‘k burchak
ax.add_patch(patches.Rectangle(
    (0, 3.23), 4.8, 2.77, color='#3C3B6E'
))

# Yulduzchalar
for row in range(5):
    for col in range(6):
        ax.text(0.4 + col * 0.75, 5.7 - row * 0.5,
                '★', color='white', fontsize=15)

ax.set_xlim(0, 12)
ax.set_ylim(0, 6)
ax.axis('off')

plt.show()