import matplotlib.pyplot as plt
import matplotlib.patches as patches

fig, ax = plt.subplots(figsize=(10, 5))

ax.add_patch(patches.Rectangle((0, 0), 12, 6, color='white'))
ax.add_patch(patches.Rectangle((0, 0.6), 12, 0.7, color='#0038B8'))
ax.add_patch(patches.Rectangle((0, 4.7), 12, 0.7, color='#0038B8'))

ax.add_patch(patches.Polygon(
    [(6, 4.1), (4.8, 2), (7.2, 2)],
    fill=False, edgecolor='#0038B8', linewidth=3
))

ax.add_patch(patches.Polygon(
    [(6, 1.9), (4.8, 4), (7.2, 4)],
    fill=False, edgecolor='#0038B8', linewidth=3
))

ax.set_xlim(0, 12)
ax.set_ylim(0, 6)
ax.axis('off')

plt.show()